#!/usr/bin/env python3
"""Phase 2 measurements. Writes data/phase2_benchmarks.{json,md}.

Compared, on the SAME program, fault model and field:
  L0  no collapsing: one obligation per fault
  L1  ordinary exact-effect collapsing (identical faulted observation)
  L2  detection-equivalence by nonzero constant scaling of g
  L3  unit-content quotient  g = u(x) R^k h, same (k, h)
  L4  L3 with all k > 0 merged (root set gains exactly {0})

Timings are wall-clock on the machine that ran this script and include
everything: symbolic derivation, witness search, quotient construction
(analyzer) and full independent re-derivation plus checks (checker).
"""
import json
import pathlib
import platform
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from cafq import circuits as C  # noqa: E402
from cafq.field import get_field  # noqa: E402
from cafq.pipeline import certify  # noqa: E402
from cafq.poly import Poly  # noqa: E402

PROGRAMS = [
    ("ar_discrepancy n=4", lambda: C.ar_discrepancy(4)),
    ("ar_discrepancy n=6", lambda: C.ar_discrepancy(6)),
    ("ar_discrepancy n=6 shift=1", lambda: C.ar_discrepancy(6, shift=1)),
    ("polymul_schoolbook n=2", lambda: C.polymul_schoolbook(2)),
    ("polymul_schoolbook n=4", lambda: C.polymul_schoolbook(4)),
    ("polymul_schoolbook n=6", lambda: C.polymul_schoolbook(6)),
    ("polymul_karatsuba2", lambda: C.polymul_karatsuba2()),
    ("butterfly4", lambda: C.butterfly4()),
]


def root_work(analysis):
    """Time the root-set computation done once per fault vs once per L4
    class (only for certificates with constant-coefficient h)."""
    prog = analysis.program
    F = get_field(prog.m, prog.modulus)
    R = prog.challenge
    hs = [(c["class_keys"]["L4"], Poly.from_json(F, c["quotient"]["h"]))
          for c in analysis.certificates
          if c["fault"] and c["quotient"] and c["quotient"]["exact_roots"] is not None]

    def roots(h):
        return [r for r in range(F.q) if h.evaluate({R: r}) == 0]
    t0 = time.perf_counter()
    for _, h in hs:
        roots(h)
    per_fault = time.perf_counter() - t0
    reps = {}
    for k, h in hs:
        reps.setdefault(k, h)
    t0 = time.perf_counter()
    for h in reps.values():
        roots(h)
    per_class = time.perf_counter() - t0
    return len(hs), len(reps), per_fault, per_class


def main():
    rows = []
    for label, build in PROGRAMS:
        prog = build()
        analysis, report = certify(prog)
        if not report["ok"]:
            raise SystemExit(f"checker rejected {label}: {report['errors'][:3]}")
        cw = [c for c in analysis.certificates if c["fault"]
              and c["classification"] == "covered" and c["wrong_output_possible"]]
        n_exact, n_cls, t_fault, t_class = root_work(analysis)
        rows.append({
            "program": label, "name": prog.name, "sha256": prog.sha256(),
            "field": f"GF({1 << prog.m})", "instructions": len(prog.instrs),
            **analysis.counts(),
            "classes_all": analysis.class_counts(False),
            "classes_covered_wrong": analysis.class_counts(True),
            "sum_naive_degree": sum(c["quotient"]["naive_degree"] for c in cw),
            "sum_certified_bound": sum(c["degree_bound"] for c in cw),
            "exact_certificates": n_exact, "exact_classes": n_cls,
            "root_enum_seconds_per_fault": t_fault,
            "root_enum_seconds_per_class": t_class,
            "analyzer_seconds": analysis.seconds,
            "checker_seconds": report["seconds"],
            "certificate_bytes": len(json.dumps(analysis.certificates)),
        })
    meta = {"python": platform.python_version(), "machine": platform.machine(),
            "system": platform.platform()}
    (ROOT / "data" / "phase2_benchmarks.json").write_text(
        json.dumps({"environment": meta, "rows": rows}, indent=1) + "\n")

    md = ["# Phase 2 measurements (generated by tools/run_benchmarks.py)", "",
          f"Environment: Python {meta['python']}, {meta['system']}.",
          "Fault model: single skip / result-zero / bit-flip on every instruction.",
          "", "## Classification (every in-scope fault counted once)", "",
          "| program | field | instrs | faults | benign | covered | of which wrong output possible | bypass | unknown |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['program']} | {r['field']} | {r['instructions']} | {r['sites']} | "
                  f"{r['benign']} | {r['covered']} | {r['covered_wrong_possible']} | "
                  f"{r['bypass']} | {r['unknown']} |")
    md += ["", "## Classes among covered faults that can corrupt the output", "",
           "| program | faults (L0) | L1 exact | L2 scale | L3 unit content | L4 +zero root | sum naive degree | sum certified bound |",
           "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        c = r["classes_covered_wrong"]
        md.append(f"| {r['program']} | {r['covered_wrong_possible']} | {c['L1']} | {c['L2']} | "
                  f"{c['L3']} | {c['L4']} | {r['sum_naive_degree']} | {r['sum_certified_bound']} |")
    md += ["", "## Classes over all in-scope faults", "",
           "| program | faults | L1 | L2 | L3 | L4 |", "|---|---|---|---|---|---|"]
    for r in rows:
        c = r["classes_all"]
        md.append(f"| {r['program']} | {r['sites']} | {c['L1']} | {c['L2']} | {c['L3']} | {c['L4']} |")
    md += ["", "## Cost", "",
           "| program | analyzer s | checker s | certificate bytes | exact root sets: per fault | per L4 class | root enum s per fault | per class |",
           "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['program']} | {r['analyzer_seconds']:.3f} | {r['checker_seconds']:.3f} | "
                  f"{r['certificate_bytes']} | {r['exact_certificates']} | {r['exact_classes']} | "
                  f"{r['root_enum_seconds_per_fault']:.4f} | {r['root_enum_seconds_per_class']:.4f} |")
    out = ROOT / "data" / "phase2_benchmarks.md"
    out.write_text("\n".join(md) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
