#!/usr/bin/env python3
"""Regenerate data/phase1_fault_matrix.md from execution (no hand-edited cells)."""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from toy import attacks, kem, scenarios  # noqa: E402

SEED = b"seed-1"
pk, sk = kem.keygen(SEED)
cases = list(scenarios.CASES)
lines = ["# Phase 1 fault-scenario matrix (generated by tools/phase1_report.py)",
         "", f"Key seed `{SEED.decode()}`, message 0x5A. Toy model; observations, not proofs.",
         "", "| variant | fault | " + " | ".join(cases) + " |",
         "|---|---|" + "---|" * len(cases)]
for shift in (0, 1):
    tab = {}
    for r in scenarios.matrix(sk, shift=shift):
        tab.setdefault((r["variant"], r["fault"]), {})[r["case"]] = r["outcome"]
    for (variant, fault), v in tab.items():
        if shift == 1 and not variant.startswith("ar"):
            continue
        lines.append(f"| {variant} | {fault} | " + " | ".join(v[c] for c in cases) + " |")

res = attacks.recover_secret_row0(lambda c: kem.decaps(sk, c, "ar").key, pk)
lines += ["", "## Coordinate-0 attack on H-AR (shift 0), no fault", "",
          f"- recovered S[0] = {res[0]}, true S[0] = {list(sk.S[0])}",
          f"- recovered E[0] = {res[1]}, true E[0] = {list(sk.E[0])}",
          f"- decapsulation queries used: {res[2]}"]
out = ROOT / "data" / "phase1_fault_matrix.md"
out.write_text("\n".join(lines) + "\n")
print(out.read_text())
